#!/usr/bin/env node
// Generates generated/tokens.ts (React Native) and generated/tokens.css (admin web) from tokens.json,
// the package copy of docs/designsystem/developer/tokens.json (single source; never edit outputs by hand).
// Usage: node scripts/generate.mjs [--check]   --check exits 1 if committed outputs drift from tokens.json.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const ROOT = new URL('../', import.meta.url);
const HEX = /^#[0-9A-Fa-f]{6}(?:[0-9A-Fa-f]{2})?$/;
const PX = /^\d+px$/;
const REQUIRED = ['color', 'deliveryStatus', 'spacing', 'radius', 'typography', 'sizing', 'shadow', 'motion', 'zIndex'];

function fail(path, msg) {
  throw new Error(`tokens.json invalid at ${path}: ${msg}`);
}

function eachLeaf(obj, path, fn) {
  for (const [k, v] of Object.entries(obj)) {
    const p = `${path}.${k}`;
    if (v && typeof v === 'object') eachLeaf(v, p, fn);
    else fn(p, v);
  }
}

// Rejects malformed input before anything is written, so a bad source edit can't produce half-valid outputs.
export function validate(tokens) {
  if (!tokens || typeof tokens !== 'object' || Array.isArray(tokens)) fail('$', 'expected an object');
  for (const key of REQUIRED) {
    if (!tokens[key] || typeof tokens[key] !== 'object') fail(key, 'missing section');
  }
  eachLeaf(tokens.color, 'color', (p, v) => HEX.test(v) || fail(p, `expected #RRGGBB[AA], got ${JSON.stringify(v)}`));
  for (const [name, s] of Object.entries(tokens.deliveryStatus)) {
    for (const k of ['bg', 'text', 'border']) {
      if (!HEX.test(s[k])) fail(`deliveryStatus.${name}.${k}`, `expected hex, got ${JSON.stringify(s[k])}`);
    }
  }
  for (const section of ['spacing', 'radius', 'sizing']) {
    eachLeaf(tokens[section], section, (p, v) => PX.test(v) || fail(p, `expected <n>px, got ${JSON.stringify(v)}`));
  }
  for (const [name, s] of Object.entries(tokens.typography.styles ?? fail('typography.styles', 'missing'))) {
    for (const k of ['size', 'lineHeight', 'weight']) {
      if (!Number.isFinite(s[k])) fail(`typography.styles.${name}.${k}`, 'expected a number');
    }
  }
  return tokens;
}

// React Native style props take unitless numbers (dp), so px strings become numbers in the TS output.
const px = (obj) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, Number.parseInt(v, 10)]));

export function renderTs(tokens, sha256) {
  const out = {
    meta: tokens.meta,
    colors: tokens.color,
    deliveryStatus: tokens.deliveryStatus,
    spacing: px(tokens.spacing),
    radii: px(tokens.radius),
    typography: tokens.typography,
    sizing: px(tokens.sizing),
    shadow: tokens.shadow,
    breakpoint: tokens.breakpoint,
    motion: tokens.motion,
    zIndex: tokens.zIndex,
  };
  const body = Object.entries(out)
    .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)} as const;\n`)
    .join('\n');
  return `${header('//', sha256)}\nexport const sourceSha256 = '${sha256}';\n\n${body}`;
}

export function renderCss(tokens, sha256) {
  const vars = [['font-sans', tokens.typography.family.primary], ['font-android', tokens.typography.family.android]];
  eachLeaf(tokens.color, 'color', (p, v) => vars.push([p.replaceAll('.', '-'), v]));
  for (const [name, s] of Object.entries(tokens.deliveryStatus)) {
    for (const k of ['bg', 'text', 'border']) vars.push([`status-${name}-${k}`, s[k]]);
  }
  for (const [k, v] of Object.entries(tokens.spacing)) vars.push([`space-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.radius)) vars.push([`radius-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.sizing)) vars.push([`size-${k}`, v]);
  for (const [k, v] of Object.entries(tokens.shadow)) vars.push([`shadow-${k}`, v]);
  for (const [name, s] of Object.entries(tokens.typography.styles)) {
    vars.push([`text-${name}-size`, `${s.size}px`], [`text-${name}-line-height`, `${s.lineHeight}px`]);
    vars.push([`text-${name}-weight`, String(s.weight)]);
  }
  for (const [k, v] of Object.entries(tokens.motion)) {
    if (k.endsWith('Ms')) vars.push([`motion-${k.slice(0, -2)}`, `${v}ms`]);
  }
  vars.push(['motion-easing', tokens.motion.easing]);
  for (const [k, v] of Object.entries(tokens.zIndex)) vars.push([`z-${k}`, String(v)]);
  const lines = vars.map(([name, value]) => `  --${name}: ${value};`).join('\n');
  return `${header('/*', sha256)}\n:root {\n  color-scheme: light;\n  --tokens-source-sha256: "${sha256}";\n${lines}\n}\n`;
}

function header(style, sha256) {
  const text = `GENERATED by packages/tokens/scripts/generate.mjs from tokens.json. Do not edit; run "npm run generate -w @dtd/tokens".\nSource sha256: ${sha256}`;
  return style === '//' ? text.split('\n').map((l) => `// ${l}`).join('\n') + '\n' : `/* ${text.replace('\n', '\n   ')} */\n`;
}

export function generate(sourceText) {
  const sha256 = createHash('sha256').update(sourceText).digest('hex');
  let tokens;
  try {
    tokens = JSON.parse(sourceText);
  } catch (e) {
    throw new Error(`tokens.json is not valid JSON: ${e.message}`);
  }
  validate(tokens);
  return { 'generated/tokens.ts': renderTs(tokens, sha256), 'generated/tokens.css': renderCss(tokens, sha256) };
}

export function run({ check = false, root = ROOT } = {}) {
  const outputs = generate(readFileSync(new URL('tokens.json', root)));
  const stale = [];
  for (const [rel, content] of Object.entries(outputs)) {
    const file = new URL(rel, root);
    if (check) {
      let current = null;
      try {
        current = readFileSync(file, 'utf8');
      } catch {
        // missing output counts as drift
      }
      if (current !== content) stale.push(rel);
    } else {
      writeFileSync(file, content);
    }
  }
  return stale;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const check = process.argv.includes('--check');
  try {
    const stale = run({ check });
    if (stale.length) {
      console.error(`tokens: out of date: ${stale.join(', ')}. Run "npm run generate -w @dtd/tokens" and commit.`);
      process.exit(1);
    }
    console.log(check ? 'tokens: generated outputs match tokens.json' : 'tokens: generated outputs written');
  } catch (e) {
    console.error(e.message);
    process.exit(1);
  }
}
